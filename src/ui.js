// « il y a 3 jours »
export function ago(ts) {
  if (!ts) return "";
  const d = Math.floor((Date.now() - ts) / 864e5);
  return d <= 0 ? "aujourd'hui" : d === 1 ? "hier" : d < 14 ? `il y a ${d} jours` : d < 60 ? `il y a ${Math.round(d / 7)} semaines` : `il y a ${Math.round(d / 30)} mois`;
}
